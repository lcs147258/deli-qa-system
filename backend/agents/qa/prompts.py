# ── ② RAG 检索策略选择器（专业问题四选一，对齐课程四策略）──────
# 返回中文策略名，core.strategy_selector 做映射与兜底；LLM 异常时默认"直接检索"。

STRATEGY_SELECT_PROMPT = """你是一个智能助手，负责分析用户查询 {query}，并从以下四种检索增强策略中选择一个最适合的策略，直接返回策略名称，不需要解释过程。

以下是几种检索增强策略及其适用场景：

1.  **直接检索：**
    * 描述：对用户查询直接进行检索，不进行任何增强处理。
    * 适用场景：查询意图明确，需要从知识库中检索特定信息的问题，含具体产品名/价格/参数/操作点。
    * 示例：
        * 查询：精品猪头肉散装多少钱一斤
        * 策略：直接检索
        * 查询：冷藏柜陈列温度多久记录一次
        * 策略：直接检索

2.  **假设问题检索：**
    * 描述：使用 LLM 先生成一个假设的答案，然后基于假设答案进行检索（HyDE）。
    * 适用场景：查询较为抽象、模糊或依赖上下文，直接检索效果不佳的问题。
    * 示例：
        * 查询：这个没懂，能再讲讲吗
        * 策略：假设问题检索
        * 查询：刚才那段是什么意思
        * 策略：假设问题检索

3.  **子查询检索：**
    * 描述：将复杂的用户查询拆分为多个简单的子查询，分别检索并合并结果。
    * 适用场景：查询涉及多个实体或多个方面，需要分别检索不同信息。
    * 示例：
        * 查询：加盟有哪些支持政策，和自己单干比有什么区别
        * 策略：子查询检索
        * 查询：卤味产品从保存、陈列到报损都有什么要求
        * 策略：子查询检索

4.  **回溯问题检索：**
    * 描述：将复杂、具体条件堆砌的查询转化为更基础、更本质的问题，然后进行检索（Step-back）。
    * 适用场景：查询过于具体或带一堆限定条件，直接检索匹配不到，需要先退一步查基础规则。
    * 示例：
        * 查询：我开在商场负一层的加盟店夏天周末卤味备货量怎么定
        * 策略：回溯问题检索
        * 查询：散装猪头肉切好摆了三个小时还能不能接着卖
        * 策略：回溯问题检索

根据用户查询 {query}，直接返回最适合的策略名称，例如 "直接检索"。不要输出任何分析过程或其他内容。"""


